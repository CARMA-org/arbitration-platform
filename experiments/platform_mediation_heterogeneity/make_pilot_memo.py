#!/usr/bin/env python3
"""Emit a concise, non-promotional results memo generated from
``results/pilot_headline.json``. Every number here is copied verbatim from the
headline, which is itself reconstructible from the raw records."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS = os.path.join(HERE, "results")
POLICIES = ["equal", "drf", "decomposed_cobb_douglas", "joint_linear",
            "joint_cobb_douglas", "joint_ces", "joint_leontief"]
NONLINEAR = ["joint_cobb_douglas", "joint_ces", "joint_leontief"]


def f(x, nd=4):
    return "n/a" if x is None or x == "" else ("%.*f" % (nd, float(x)))


def load():
    with open(os.path.join(RESULTS, "pilot_headline.json")) as f_:
        return json.load(f_)


def workload_section(h):
    L = ["## Workload-concentration sweep", ""]
    cells = h["workload"]["cells"]
    diss = h["workload"]["dissimilarity"]

    L.append("### Completion by policy and cell (completion fraction)")
    L.append("")
    L.append("| cell | " + " | ".join(POLICIES) + " |")
    L.append("|" + "---|" * (len(POLICIES) + 1))
    for cell in sorted(cells):
        row = cells[cell]
        vals = [f(row.get(p, {}).get("completion_mean")) for p in POLICIES]
        L.append("| %s | %s |" % (cell, " | ".join(vals)))
    L.append("")

    L.append("### Paired difference vs DRF and vs equal (tasks per 48-task run), 95% bootstrap CI")
    L.append("")
    L.append("| cell | policy | diff vs DRF (tasks) | 95% CI (frac) | diff vs equal (tasks) | 95% CI (frac) |")
    L.append("|---|---|---|---|---|---|")
    for cell in sorted(cells):
        for p in NONLINEAR + ["joint_linear"]:
            r = cells[cell].get(p)
            if not r:
                continue
            L.append("| %s | %s | %s | [%s, %s] | %s | [%s, %s] |" % (
                cell, p, f(r["diff_vs_drf_tasks"], 3),
                f(r["diff_vs_drf_ci_lo"], 4), f(r["diff_vs_drf_ci_hi"], 4),
                f(r["diff_vs_equal_tasks"], 3),
                f(r["diff_vs_equal_ci_lo"], 4), f(r["diff_vs_equal_ci_hi"], 4)))
    L.append("")

    L.append("### Realized dissimilarity and health by cell")
    L.append("")
    L.append("| regime|contention | resource-demand TV mean | task-mixture TV mean | task entropy | frac all-4 | realized contention |")
    L.append("|---|---|---|---|---|---|")
    for k in sorted(diss):
        d = diss[k]
        L.append("| %s | %s | %s | %s | %s | %s |" % (
            k, f(d["resource_demand_tv_mean"], 4), f(d["task_mixture_tv_mean"], 4),
            f(d["task_entropy_mean"], 4), f(d["frac_all_four_mean"], 3),
            f(d["mean_realized_contention"], 4)))
    L.append("")

    L.append("### Worst-agent and zero-completion (nonlinear + joint_linear) by cell")
    L.append("")
    L.append("| cell | policy | frac zero-completion | frac worse than equal | min agent completion | p5 agent completion |")
    L.append("|---|---|---|---|---|---|")
    for cell in sorted(cells):
        for p in NONLINEAR + ["joint_linear"]:
            r = cells[cell].get(p)
            if not r:
                continue
            L.append("| %s | %s | %s | %s | %s | %s |" % (
                cell, p, f(r.get("frac_zero_completion"), 3), f(r.get("frac_worse_than_equal"), 3),
                f(r.get("agent_completion_min"), 3), f(r.get("agent_completion_p5"), 3)))
    L.append("")
    return L


def floor_section(h):
    L = ["## Floor-sensitivity sweep", ""]
    cells = h["floor"]["cells"]
    L.append("| floor|regime|contention | policy | completion | diff vs equal (tasks) | diff vs DRF (tasks) | frac zero | frac worse than equal | frac alloc cells at floor | cap util | infeasible |")
    L.append("|---|---|---|---|---|---|---|---|---|---|")
    for cell in sorted(cells):
        for p in ["equal", "drf", "joint_linear"]:
            r = cells[cell].get(p)
            if not r:
                continue
            L.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
                cell, p, f(r["completion_mean"], 4), f(r["diff_vs_equal_tasks"], 3),
                f(r["diff_vs_drf_tasks"], 3), f(r.get("frac_zero_completion"), 3),
                f(r.get("frac_worse_than_equal"), 3), f(r.get("frac_alloc_cells_at_lower"), 3),
                f(r.get("capacity_utilization"), 3), r.get("infeasible_runs")))
    L.append("")
    return L


def main():
    h = load()
    L = ["# Pilot results memo (machine-generated)", "",
         "Generated by `make_pilot_memo.py` from `results/pilot_headline.json`. "
         "Numbers are copied from the headline; no interpretation is added here. "
         "Completion is the mean fraction of an agent's 8 tasks completed; one run "
         "has %d tasks. Differences are paired by task-workload seed within a cell." % h["tasks_per_run"],
         ""]
    if "workload" in h:
        L += workload_section(h)
    if "floor" in h:
        L += floor_section(h)
    out = os.path.join(RESULTS, "PILOT_MEMO.md")
    with open(out, "w") as fh:
        fh.write("\n".join(L).rstrip("\n") + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
